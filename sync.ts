import { writeFile } from "node:fs/promises"

export const TELEGRAM_BOT_API_URL = "https://core.telegram.org/bots/api"
export const TELEGRAM_BOT_CURRENCIES_URL = "https://core.telegram.org/bots/payments/currencies.json"
export const TELEGRAM_BOT_API_CHANGELOG_URL = "https://core.telegram.org/bots/api-changelog"

export interface DocSection {
  name: string
  anchor: string
  html: string
  text: string
  fields: DocField[]
}

export interface DocField {
  name: string
  type: string
  required?: boolean
  description: string
}

export interface ApiModel {
  sections: DocSection[]
  types: GeneratedType[]
  methods: GeneratedMethod[]
}

export interface GeneratedType {
  kind: "interface" | "union" | "alias"
  name: string
  source: string
}

export interface GeneratedMethod {
  name: string
  optionsName: string
  returnType: string
  fields: DocField[]
  hasUpload: boolean
  source: string[]
}

const reservedTypeNames = new Set([
  "Array",
  "Boolean",
  "Float",
  "Integer",
  "String",
  "True",
])

export async function sync() {
  const html = await fetchText(TELEGRAM_BOT_API_URL)
  const currenciesJSON = await fetchText(TELEGRAM_BOT_CURRENCIES_URL)
  const changelogHtml = await fetchText(TELEGRAM_BOT_API_CHANGELOG_URL)
  const source = generateIndexSource(parseBotApiHtml(html))
  const changelog = generateChangelogMarkdown(changelogHtml)

  await writeFile("api.ts", source)
  await writeFile("currencies.json", currenciesJSON)
  await writeFile("CHANGELOG.md", changelog)

  return source
}

async function fetchText(url: string) {
  const response = await global.fetch(url)
  const text = await response.text()

  if (!response.ok) {
    throw new Error(text)
  }

  return text
}

export function parseBotApiHtml(html: string): ApiModel {
  const sections = parseSections(html)
  const types = generateTypes(sections)
  const methods = generateMethods(sections)

  return {
    sections,
    types,
    methods,
  }
}

export function generateIndexSource(model: ApiModel): string {
  return [
    "// This file was generated by sync.ts from https://core.telegram.org/bots/api",
    `import { prepareFormBody, prepareFormHeaders, parseResponse, TelegramError } from "./helpers.js"`,
    "",
    "/**",
    " * Types",
    " */",
    "export type InputFile = Blob | string",
    "",
    "/**",
    " * Helper Types",
    " */",

    "",
    ...model.types.map(function (type) {
      return type.source
    }),
    "/**",
    " * Methods",
    " */",
    "const headers = {",
    "  \"Accept\": \"application/json\",",
    "  \"Content-Type\": \"application/json\",",
    "}",
    "",
    ...model.methods.flatMap(function (method) {
      return method.source
    }),
    // helpersSource(),
  ].join("\n")
}

export function parseSections(html: string): DocSection[] {
  const matches = [...html.matchAll(/<h4><a class="anchor" name="([^"]+)"[^>]*>[\s\S]*?<\/a>([\s\S]*?)<\/h4>/g)]
  const sections: DocSection[] = []

  for (let index = 0; index < matches.length; index++) {
    const match = matches[index]
    const next = matches[index + 1]
    const start = match.index ?? 0
    const end = next?.index ?? html.length
    const source = html.slice(start, end)
    const name = toText(match[2])

    if (!name) {
      continue
    }

    sections.push({
      name,
      anchor: match[1],
      html: source,
      text: toText(source),
      fields: parseFieldTable(source),
    })
  }

  return sections
}

export function parseFieldTable(sectionHtml: string): DocField[] {
  const fields: DocField[] = []

  for (const row of sectionHtml.matchAll(/<tr>([\s\S]*?)<\/tr>/g)) {
    const cells = [...row[1].matchAll(/<t[dh][^>]*>([\s\S]*?)<\/t[dh]>/g)].map(function (cell) {
      return toText(cell[1])
    })

    if (cells.length < 3 || cells[0] === "Field" || cells[0] === "Parameter") {
      continue
    }

    if (!/^[a-zA-Z_][a-zA-Z0-9_]*$/.test(cells[0])) {
      continue
    }

    fields.push({
      name: cells[0],
      type: cells[1],
      required: cells.length >= 4 ? cells[2] === "Yes" : undefined,
      description: cells.length >= 4 ? cells[3] : cells[2],
    })
  }

  return fields
}

export function generateTypes(sections: DocSection[]): GeneratedType[] {
  const sectionByName = new Map(sections.map(function (section) {
    return [section.name, section]
  }))
  const types: GeneratedType[] = []

  for (const section of sections) {
    if (!isTypeSection(section)) {
      continue
    }

    const unionMembers = parseUnionMembers(section)

    if (unionMembers.length > 0) {
      types.push({
        kind: "union",
        name: section.name,
        source: renderUnion(section.name, unionMembers),
      })
      continue
    }

    if (section.name === "InputFile") {
      continue
    }

    if (section.fields.length === 0) {
      types.push({
        kind: "interface",
        name: section.name,
        source: `export interface ${section.name} {\n}\n`,
      })
      continue
    }

    types.push({
      kind: "interface",
      name: section.name,
      source: renderInterface(section.name, section.fields, sectionByName),
    })
  }

  return dedupeGeneratedTypes(types)
}

export function generateMethods(sections: DocSection[]): GeneratedMethod[] {
  return sections
    .filter(isMethodSection)
    .map(function (section) {
      const optionsName = `${toPascalCase(section.name)}Options`
      const returnType = parseReturnType(section.text)
      const hasUpload = section.fields.some(function (field) {
        const scriptType = toTypeScriptType(field)

        return scriptType.includes("InputFile") || scriptType.includes("InputMedia")
      })
      const options = renderOptionsInterface(optionsName, section.fields)
      const payloadType = hasUpload ? `${optionsName} | FormData` : optionsName
      const bodyExpression = hasUpload ? "prepareFormBody(payload)" : "JSON.stringify(payload)"
      const headersExpression = hasUpload ? "prepareFormHeaders(payload)" : "headers"
      const source = [
        options,
        "",
        `export function ${section.name}(token: string, payload: ${payloadType}, signal?: AbortSignal) {`,
        `  return fetch(\`https://api.telegram.org/bot\${token}/${section.name}\`, {`,
        "    method: \"POST\",",
        `    body: ${bodyExpression},`,
        `    headers: ${headersExpression},`,
        "    signal",
        `  }).then(parseResponse<${returnType}>)`,
        "}",
        "",
      ]

      return {
        name: section.name,
        optionsName,
        returnType,
        fields: section.fields,
        hasUpload,
        source,
      }
    })
}

export function toTypeScriptType(field: Pick<DocField, "type" | "description">): string {
  const literalUnion = parseLiteralUnion(field.description)

  if (literalUnion.length > 0 && /^String\b/.test(field.type)) {
    return literalUnion.map(function (value) {
      return JSON.stringify(value)
    }).join(" | ")
  }

  return normalizeType(field.type)
}

export function normalizeType(type: string): string {
  const arrayMatch = type.match(/^Array of (.+)$/)

  if (arrayMatch) {
    if (arrayMatch[1].startsWith("Array of ")) {
      return `${normalizeType(arrayMatch[1])}[]`
    }

    const arrayMembers = splitTypeList(arrayMatch[1])

    if (arrayMembers.length > 1) {
      return `Array<${arrayMembers.map(normalizeType).join(" | ")}>`
    }

    return `${normalizeType(arrayMatch[1])}[]`
  }

  let value = type
    .replace(/\bInteger or String\b/g, "number | string")
    .replace(/\bString or Integer\b/g, "string | number")
    .replace(/\bInputFile or String\b/g, "InputFile | string")
    .replace(/\bString or InputFile\b/g, "string | InputFile")
    .replace(/\bInteger\b/g, "number")
    .replace(/\bFloat\b/g, "number")
    .replace(/\bBoolean\b/g, "boolean")
    .replace(/\bTrue\b/g, "boolean")
    .replace(/\bString\b/g, "string")
    .replace(/\bNothing\b/g, "void")
    .replace(/\bor\b/g, "|")

  value = value.replace(/,\s*/g, " | ")
  value = value.replace(/\s*\|\s*/g, " | ")

  return value
}

function renderUnion(name: string, members: string[]) {
  return `export type ${name} = ${members.join("\n  | ")}\n`
}

function renderInterface(name: string, fields: DocField[], sectionByName: Map<string, DocSection>) {
  const lines = fields.flatMap(function (field) {
    const optional = isOptionalField(field) ? "?" : ""
    const type = renderFieldType(field, sectionByName)
    return [
      ...renderJSDoc(field.description, "  "),
      `  ${field.name}${optional}: ${type}`,
    ]
  })

  return [
    `export interface ${name} {`,
    ...lines,
    "}",
    "",
  ].join("\n")
}

function renderOptionsInterface(name: string, fields: DocField[]) {
  const lines = fields.flatMap(function (field) {
    const optional = field.required === false ? "?" : ""
    return [
      ...renderJSDoc(field.description, "  "),
      `  ${field.name}${optional}: ${toTypeScriptType(field)}`,
    ]
  })

  return [
    `export interface ${name} {`,
    ...lines,
    "}",
  ].join("\n")
}

function renderFieldType(field: DocField, sectionByName: Map<string, DocSection>) {
  const constantValue = parseConstantTypeValue(field)

  if (constantValue) {
    return JSON.stringify(constantValue)
  }

  const unionMembers = parseLiteralUnion(field.description)

  if (field.type === "String" && unionMembers.length > 0) {
    return unionMembers.map(function (member) {
      return JSON.stringify(member)
    }).join(" | ")
  }

  const type = toTypeScriptType(field)

  if (type === field.name && sectionByName.has(type)) {
    return `${type}Value`
  }

  return type
}

function renderJSDoc(description: string, indent = "") {
  const text = description.replace(/\*\//g, "* /").trim()

  if (!text) {
    return []
  }

  return [
    `${indent}/**`,
    `${indent} * ${text}`,
    `${indent} */`,
  ]
}

export function generateChangelogMarkdown(html: string) {
  const body = extractChangelogBody(html)
  const lines = [
    "# Bot API changelog",
    "",
    `_Source: ${TELEGRAM_BOT_API_CHANGELOG_URL}_`,
    "",
  ]
  const tokenPattern = /<(h3|h4)[^>]*>([\s\S]*?)<\/\1>|<p[^>]*>([\s\S]*?)<\/p>|<li[^>]*>([\s\S]*?)<\/li>/gi

  for (const token of body.matchAll(tokenPattern)) {
    const heading = token[1]

    if (heading === "h3") {
      ensureBlankLine(lines)
      lines.push(`## ${inlineHtmlToMarkdown(token[2])}`, "")
      continue
    }

    if (heading === "h4") {
      ensureBlankLine(lines)
      lines.push(`### ${inlineHtmlToMarkdown(token[2])}`, "")
      continue
    }

    if (token[3]) {
      const paragraph = inlineHtmlToMarkdown(token[3])

      if (paragraph) {
        ensureBlankLine(lines)
        lines.push(paragraph, "")
      }

      continue
    }

    if (token[4]) {
      const item = inlineHtmlToMarkdown(token[4])

      if (item) {
        lines.push(`- ${item}`)
      }
    }
  }

  return normalizeMarkdown(lines.join("\n"))
}

function ensureBlankLine(lines: string[]) {
  if (lines.length > 0 && lines[lines.length - 1] !== "") {
    lines.push("")
  }
}

function extractChangelogBody(html: string) {
  const start = html.indexOf("<h3")
  const footer = html.indexOf("<div class=\"footer_wrap\"", start)

  if (start === -1) {
    return html
  }

  if (footer === -1) {
    return html.slice(start)
  }

  return html.slice(start, footer)
}

function inlineHtmlToMarkdown(html: string): string {
  let value: string = html
    .replace(/<a\s+[^>]*href="([^"]+)"[^>]*>([\s\S]*?)<\/a>/gi, function (match, href, label) {
      const text = inlineHtmlToMarkdown(label)

      if (!text) {
        return ""
      }

      return `[${text}](${resolveTelegramUrl(href)})`
    })
    .replace(/<(strong|b)>([\s\S]*?)<\/\1>/gi, function (match, tag, content) {
      return `**${inlineHtmlToMarkdown(content)}**`
    })
    .replace(/<em>([\s\S]*?)<\/em>/gi, function (match, content) {
      return `_${inlineHtmlToMarkdown(content)}_`
    })
    .replace(/<code>([\s\S]*?)<\/code>/gi, function (match, content) {
      return `\`${toText(content).replace(/`/g, "\\`")}\``
    })
    .replace(/<br\s*\/?>/gi, " ")
    .replace(/<[^>]+>/g, " ")

  value = decodeHtmlEntities(value)
    .replace(/\s+/g, " ")
    .replace(/\s+([.,;:!?])/g, "$1")
    .trim()

  return value
}

function resolveTelegramUrl(href: string): string {
  if (/^https?:\/\//.test(href)) {
    return href
  }

  if (href.startsWith("//")) {
    return `https:${href}`
  }

  if (href.startsWith("/")) {
    return `https://core.telegram.org${href}`
  }

  return href
}

function normalizeMarkdown(markdown: string): string {
  return `${markdown
    .replace(/[ \t]+\n/g, "\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim()}\n`
}

function parseUnionMembers(section: DocSection) {
  if (section.fields.length > 0) {
    return []
  }

  const names = [...section.html.matchAll(/<a href="#[^"]+">([A-Z][A-Za-z0-9]+)<\/a>/g)]
    .map(function (match) {
      return match[1]
    })
    .filter(function (name) {
      return name !== section.name && !reservedTypeNames.has(name)
    })

  const unique = [...new Set(names)]

  if (/it can be either a String/.test(section.text)) {
    unique.unshift("string")
  }

  if (/an Array of RichText/.test(section.text)) {
    unique.unshift("RichText[]")
  }

  if (!/can be one of|following types|should be one of|can be either/i.test(section.text)) {
    return []
  }

  return unique
}

function splitTypeList(value: string) {
  return value
    .replace(/\s+and\s+/g, ",")
    .replace(/\s+or\s+/g, ",")
    .split(",")
    .map(function (item) {
      return item.trim()
    })
    .filter(Boolean)
}

function parseReturnType(text: string) {
  if (text.startsWith("getMe")) {
    return "User"
  }

  if (text.startsWith("getWebhookInfo")) {
    return "WebhookInfo"
  }

  if (text.startsWith("copyMessage")) {
    return "MessageId"
  }

  if (text.startsWith("exportChatInviteLink")
    || text.startsWith("createChatInviteLink")
    || text.startsWith("getManagedBotToken")
    || text.startsWith("replaceManagedBotToken")
    || text.startsWith("createInvoiceLink")
  ) {
    return "string"
  }

  if (text.startsWith("editChatInviteLink")
    || text.startsWith("createChatSubscriptionInviteLink")
    || text.startsWith("editChatSubscriptionInviteLink")
    || text.startsWith("revokeChatInviteLink")
  ) {
    return "ChatInviteLink"
  }

  if (text.startsWith("createForumTopic")) {
    return "ForumTopic"
  }

  if (text.startsWith("uploadStickerFile")) {
    return "File"
  }

  if (text.startsWith("getMyStarBalance")) {
    return "StarAmount"
  }

  if (text.startsWith("getStarTransactions")) {
    return "StarTransactions"
  }

  const returnObject = text.match(/Returns a ([A-Z][A-Za-z0-9]+)\s+object/)

  if (returnObject) {
    return returnObject[1]
  }

  const editableResult = text.match(/([A-Z][A-Za-z0-9]+)\s+is returned, otherwise True is returned/)

  if (editableResult) {
    return `${editableResult[1]} | boolean`
  }

  const arrayResult = text.match(/(?:On success|Returns)[^.]*?\b[Aa]rray of ([A-Z][A-Za-z0-9]+?)(?:s\b|\b)(?: objects?)?/)

  if (arrayResult) {
    return `${arrayResult[1]}[]`
  }

  const result = text.match(/On success,[^.]*?\b([A-Z][A-Za-z0-9]*(?:\[\])?)\b[^.]*?is returned/)
    ?? text.match(/Returns\s+(?:an?|the)?\s*([A-Z][A-Za-z0-9]*(?:\[\])?)\s+on success/)

  if (result) {
    return normalizeType(result[1])
  }

  if (/Returns True on success/i.test(text)) {
    return "boolean"
  }

  throw new TypeError("fail to parse return type", {
    cause: new Error(text)
  })
}

function parseConstantTypeValue(field: DocField) {
  if (field.name !== "type" && field.name !== "source" && field.name !== "status") {
    return
  }

  const oneOfUnion = field.description.match(/(?:must be one of)\s+"([^"]+)"/i)

  if (oneOfUnion) {
    return
  }

  const quoted = field.description.match(/(?:always|must be)\s+"([^"]+)"/i)

  if (quoted) {
    return quoted[1]
  }

  const unquoted = field.description.match(/(?:always|must be)\s+([a-z][a-z0-9_]+)/i)

  return unquoted?.[1]
}

function parseLiteralUnion(description: string) {
  if (!/currently|can be|must be one of|can be either/i.test(description)) {
    return []
  }

  const quoted = [...description.matchAll(/"([^"]+)"/g)].map(function (match) {
    return match[1]
  })

  return [...new Set(quoted)]
}

function isOptionalField(field: DocField) {
  return field.description.startsWith("Optional")
    || /\bOptional\b/.test(field.description)
    || field.required === false
}

function isTypeSection(section: DocSection) {
  return /^[A-Z][A-Za-z0-9]*$/.test(section.name)
}

function isMethodSection(section: DocSection) {
  return /^[a-z][A-Za-z0-9]*$/.test(section.name) && /Use this method|Returns|On success/i.test(section.text)
}

function dedupeGeneratedTypes(types: GeneratedType[]) {
  const seen = new Set<string>()

  return types.filter(function (type) {
    if (seen.has(type.name)) {
      return false
    }

    seen.add(type.name)

    return true
  })
}

function toPascalCase(value: string) {
  return `${value[0].toUpperCase()}${value.slice(1)}`
}

function toText(html: string) {
  return decodeHtmlEntities(html
    .replace(/<br\s*\/?>/gi, "\n")
    .replace(/<img\b[^>]*>/gi, function (image) {
      const alt = image.match(/\balt\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s>]+))/i)

      return alt ? alt[1] ?? alt[2] ?? alt[3] : ""
    })
    .replace(/<[^>]+>/g, ""))
    .replace(/\s+/g, " ")
    .trim()
}

function decodeHtmlEntities(value: string) {
  return value
    .replace(/&quot;/g, "\"")
    .replace(/&#39;/g, "'")
    .replace(/&ldquo;|&rdquo;|“|”/g, "\"")
    .replace(/&lsquo;|&rsquo;|‘|’/g, "'")
    .replace(/&nbsp;/g, " ")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&amp;/g, "&")
    .replace(/&mdash;/g, "-")
    .replace(/&ndash;/g, "-")
    .replace(/&hellip;/g, "...")
}


function isMainModule() {
  return process.argv[1] ? import.meta.url === new URL(process.argv[1], "file:").href : false
}

if (isMainModule()) {
  sync().catch(function (err) {
    console.error(err)
    process.exitCode = 1
  })
}
